// Original, compact practice architecture. Coordinates are native 320 × 180;
// spawn is the top-left of the 8 × 11 player collider, not a foot position.
const block = (x, y, w, h = 180 - y, kind = 'solid') => ({ x, y, w, h, kind });
const flag = (x, floor, requires, extra = {}) => ({ x, y: floor - 23, w: 16, h: 23, requires, ...extra });
const refill = (id, x, y) => ({ id, type: 'refill', x, y, dashes: 1, respawn: 2.5 });
const path = (...points) => points.map(([x, y, kind = 'move']) => ({ x, y, kind }));
const chapters = ['初雪 · 基础', '石壁 · 借力', '长风 · 地面技', '飞线 · 空中技', '针眼 · 精确技', '回声 · 综合', '折线 · 复合技', '浮风 · 惯性'];
function lesson(index, data) {
  return {
    id: `${String(index).padStart(2, '0')}-${data.slug}`,
    chapter: Math.floor((index - 1) / 4) + 1,
    category: chapters[Math.floor((index - 1) / 4)],
    level: index <= 8 ? 1 : index <= 12 ? 2 : index <= 16 ? 3 : index <= 21 ? 4 : 5,
    hazards: [{ x: 0, y: 176, w: 320, h: 4, kind: 'spikes', direction: 'up' }],
    entities: [], ...data,
    requiredTech: [...data.goal.requires],
  };
}

